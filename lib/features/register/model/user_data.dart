  final String completeName;
  final String email;
  final String cpf;
  final String phone;
  final String street;
  final String number;
  final String cep;
  final String state;
  final String city;
  final String complement;

  PersonalData({
    required this.completeName,
    required this.email,
    required this.cpf,
    required this.phone,
    required this.street,
    required this.number,
    required this.cep,
    required this.state,
    required this.city,
    required this.complement,
  });
}

